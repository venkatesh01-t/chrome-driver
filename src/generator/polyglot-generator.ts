import { TestCaseModel, TestStep, LocatorCandidate } from '../types/model';
import { isPasswordStep } from './python-generator';

/**
 * Format a LocatorCandidate into a TypeScript Playwright locator string
 */
export function formatPlaywrightTsLocator(candidate: LocatorCandidate): string {
  const { strategy, value } = candidate;
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

  switch (strategy) {
    case 'id':
      return `"#${escaped}"`;
    case 'name':
      return `"[name=\\"${escaped}\\"]"`;
    case 'data-testid':
      return `"[data-testid=\\"${escaped}\\"]"`;
    case 'aria-label':
      return `"[aria-label=\\"${escaped}\\"]"`;
    case 'xpath':
    case 'absolute-xpath':
      return `"xpath=${escaped}"`;
    case 'css':
    default:
      return `"${escaped}"`;
  }
}

/**
 * Format a LocatorCandidate into a Cypress locator string
 */
export function formatCypressLocator(candidate: LocatorCandidate): string {
  const { strategy, value } = candidate;
  const escaped = value.replace(/'/g, "\\'");

  switch (strategy) {
    case 'id':
      return `'#${escaped}'`;
    case 'name':
      return `'[name="${escaped}"]'`;
    case 'data-testid':
      return `'[data-testid="${escaped}"]'`;
    case 'aria-label':
      return `'[aria-label="${escaped}"]'`;
    case 'xpath':
    case 'absolute-xpath':
      return `'xpath=${escaped}'`;
    case 'css':
    default:
      return `'${escaped}'`;
  }
}

/**
 * Format a LocatorCandidate into a Java By selector string
 */
export function formatJavaBy(candidate: LocatorCandidate): string {
  const { strategy, value } = candidate;
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

  switch (strategy) {
    case 'id':
      return `By.id("${escaped}")`;
    case 'name':
      return `By.name("${escaped}")`;
    case 'xpath':
    case 'absolute-xpath':
      return `By.xpath("${escaped}")`;
    case 'css':
    case 'data-testid':
    case 'aria-label':
    default:
      if (strategy === 'data-testid') return `By.cssSelector("[data-testid=\\"${escaped}\\"]")`;
      if (strategy === 'aria-label') return `By.cssSelector("[aria-label=\\"${escaped}\\"]")`;
      return `By.cssSelector("${escaped}")`;
  }
}

function getPrimaryCandidate(step: TestStep): LocatorCandidate {
  const locs = step.target?.locators;
  if (!locs || locs.length === 0) {
    return {
      strategy: 'css',
      value: step.target?.tagName || 'body',
      isUnique: false,
      matchCount: 1,
      score: 50,
    };
  }
  const idx = step.target.selectedLocatorIndex ?? 0;
  return locs[idx] || locs[0];
}

/**
 * Generates an Enterprise-grade Playwright TypeScript (@playwright/test) spec
 */
export function generatePlaywrightTs(testCase: TestCaseModel): string {
  const lines: string[] = [];
  const testName = testCase.name || 'Enterprise E2E Journey';
  const url = testCase.url || 'about:blank';
  const timeoutMs = (testCase.settings?.timeout ?? 10) * 1000;
  const maskSensitive = testCase.settings?.maskSensitiveData ?? true;

  lines.push(`import { test, expect, Page } from '@playwright/test';`);
  lines.push('');
  lines.push(`/**`);
  lines.push(` * Automated E2E Test Suite: ${testName}`);
  lines.push(` * Generated by Chrome E2E Recorder (Master Edition)`);
  lines.push(` * Target: ${url}`);
  lines.push(` */`);
  lines.push(`test.describe('${testName}', () => {`);
  lines.push(`  test.setTimeout(${timeoutMs * 2});`);
  lines.push('');
  lines.push(`  test('should execute recorded workflow successfully', async ({ page }) => {`);
  lines.push(`    // 1. Navigation & Viewport Baseline`);
  lines.push(`    await page.goto('${url}', { waitUntil: 'domcontentloaded' });`);
  lines.push('');

  testCase.steps.forEach((step, idx) => {
    const cand = getPrimaryCandidate(step);
    const sel = formatPlaywrightTsLocator(cand);
    const comment = `    // Step ${idx + 1}: ${step.action.toUpperCase()} on <${step.target?.tagName || 'el'}>`;
    lines.push(comment);

    switch (step.action) {
      case 'click':
        lines.push(`    await page.locator(${sel}).click();`);
        break;

      case 'type': {
        const isSecret = maskSensitive && isPasswordStep(step);
        const val = isSecret ? `process.env.TEST_PASSWORD || '${step.value || ''}'` : JSON.stringify(step.value || '');
        lines.push(`    await page.locator(${sel}).fill(${val});`);
        break;
      }

      case 'clear':
        lines.push(`    await page.locator(${sel}).clear();`);
        break;

      case 'checkbox':
      case 'radio':
        if (step.action === 'radio' || step.value === 'true' || !step.value) {
          lines.push(`    await page.locator(${sel}).check();`);
        } else {
          lines.push(`    await page.locator(${sel}).uncheck();`);
        }
        break;

      case 'select':
        lines.push(`    await page.locator(${sel}).selectOption(${JSON.stringify(step.value || '')});`);
        break;

      case 'hover':
        lines.push(`    await page.locator(${sel}).hover();`);
        break;

      case 'scroll':
        lines.push(`    await page.locator(${sel}).scrollIntoViewIfNeeded();`);
        break;

      case 'assert_visible':
        lines.push(`    await expect(page.locator(${sel})).toBeVisible({ timeout: ${timeoutMs} });`);
        break;

      case 'assert_text':
        lines.push(`    await expect(page.locator(${sel})).toContainText(${JSON.stringify(step.assertExpected || '')});`);
        break;

      case 'assert_attribute':
        lines.push(`    await expect(page.locator(${sel})).toHaveAttribute('${step.assertAttribute || 'data-status'}', ${JSON.stringify(step.assertExpected || '')});`);
        break;

      case 'navigate':
        lines.push(`    await page.goto(${JSON.stringify(step.value || url)});`);
        break;

      case 'wait':
        lines.push(`    await page.waitForTimeout(${(step.waitDuration ?? 1) * 1000});`);
        break;

      default:
        lines.push(`    await page.locator(${sel}).click();`);
        break;
    }
    lines.push('');
  });

  lines.push(`  });`);
  lines.push(`});`);
  return lines.join('\n');
}

/**
 * Generates modern Cypress TypeScript test code
 */
export function generateCypress(testCase: TestCaseModel): string {
  const lines: string[] = [];
  const testName = testCase.name || 'Cypress Automated Spec';
  const url = testCase.url || 'about:blank';

  lines.push(`/// <reference types="cypress" />`);
  lines.push('');
  lines.push(`describe('${testName}', () => {`);
  lines.push(`  beforeEach(() => {`);
  lines.push(`    cy.visit('${url}');`);
  lines.push(`  });`);
  lines.push('');
  lines.push(`  it('passes recorded user interactions', () => {`);

  testCase.steps.forEach((step, idx) => {
    const cand = getPrimaryCandidate(step);
    const sel = formatCypressLocator(cand);
    const isXpath = cand.strategy === 'xpath' || cand.strategy === 'absolute-xpath';
    const getExpr = isXpath ? `cy.xpath(${sel.replace('xpath=', '')})` : `cy.get(${sel})`;

    lines.push(`    // Step ${idx + 1}: ${step.action}`);
    switch (step.action) {
      case 'click':
        lines.push(`    ${getExpr}.should('be.visible').click();`);
        break;

      case 'type':
        lines.push(`    ${getExpr}.clear().type(${JSON.stringify(step.value || '')});`);
        break;

      case 'clear':
        lines.push(`    ${getExpr}.clear();`);
        break;

      case 'checkbox':
      case 'radio':
        if (step.action === 'radio' || step.value === 'true' || !step.value) {
          lines.push(`    ${getExpr}.check();`);
        } else {
          lines.push(`    ${getExpr}.uncheck();`);
        }
        break;

      case 'select':
        lines.push(`    ${getExpr}.select(${JSON.stringify(step.value || '')});`);
        break;

      case 'hover':
        lines.push(`    ${getExpr}.trigger('mouseover');`);
        break;

      case 'assert_visible':
        lines.push(`    ${getExpr}.should('be.visible');`);
        break;

      case 'assert_text':
        lines.push(`    ${getExpr}.should('contain.text', ${JSON.stringify(step.assertExpected || '')});`);
        break;

      case 'wait':
        lines.push(`    cy.wait(${(step.waitDuration ?? 1) * 1000});`);
        break;

      default:
        lines.push(`    ${getExpr}.click();`);
        break;
    }
  });

  lines.push(`  });`);
  lines.push(`});`);
  return lines.join('\n');
}

/**
 * Generates an Enterprise Java Selenium 4 + TestNG test class
 */
export function generateSeleniumJava(testCase: TestCaseModel): string {
  const lines: string[] = [];
  const rawName = (testCase.name || 'AutomatedE2ETest').replace(/[^a-zA-Z0-9]/g, '');
  const className = rawName ? rawName.charAt(0).toUpperCase() + rawName.slice(1) : 'AutomatedTest';
  const url = testCase.url || 'about:blank';
  const timeoutSec = testCase.settings?.timeout ?? 10;

  lines.push(`package com.company.qa.tests;`);
  lines.push('');
  lines.push(`import org.openqa.selenium.By;`);
  lines.push(`import org.openqa.selenium.WebDriver;`);
  lines.push(`import org.openqa.selenium.WebElement;`);
  lines.push(`import org.openqa.selenium.chrome.ChromeDriver;`);
  lines.push(`import org.openqa.selenium.chrome.ChromeOptions;`);
  lines.push(`import org.openqa.selenium.support.ui.ExpectedConditions;`);
  lines.push(`import org.openqa.selenium.support.ui.WebDriverWait;`);
  lines.push(`import org.testng.Assert;`);
  lines.push(`import org.testng.annotations.AfterMethod;`);
  lines.push(`import org.testng.annotations.BeforeMethod;`);
  lines.push(`import org.testng.annotations.Test;`);
  lines.push(`import java.time.Duration;`);
  lines.push('');
  lines.push(`public class ${className} {`);
  lines.push(`    private WebDriver driver;`);
  lines.push(`    private WebDriverWait wait;`);
  lines.push('');
  lines.push(`    @BeforeMethod`);
  lines.push(`    public void setUp() {`);
  lines.push(`        ChromeOptions options = new ChromeOptions();`);
  lines.push(`        options.addArguments("--disable-blink-features=AutomationControlled");`);
  lines.push(`        driver = new ChromeDriver(options);`);
  lines.push(`        driver.manage().window().maximize();`);
  lines.push(`        wait = new WebDriverWait(driver, Duration.ofSeconds(${timeoutSec}));`);
  lines.push(`        driver.get("${url}");`);
  lines.push(`    }`);
  lines.push('');
  lines.push(`    @Test`);
  lines.push(`    public void testRecordedUserJourney() {`);

  testCase.steps.forEach((step, idx) => {
    const cand = getPrimaryCandidate(step);
    const byExpr = formatJavaBy(cand);
    lines.push(`        // Step ${idx + 1}: ${step.action}`);

    switch (step.action) {
      case 'click':
        lines.push(`        wait.until(ExpectedConditions.elementToBeClickable(${byExpr})).click();`);
        break;

      case 'type': {
        const val = JSON.stringify(step.value || '');
        lines.push(`        WebElement el${idx} = wait.until(ExpectedConditions.visibilityOfElementLocated(${byExpr}));`);
        lines.push(`        el${idx}.clear();`);
        lines.push(`        el${idx}.sendKeys(${val});`);
        break;
      }

      case 'assert_visible':
        lines.push(`        Assert.assertTrue(wait.until(ExpectedConditions.visibilityOfElementLocated(${byExpr})).isDisplayed());`);
        break;

      case 'assert_text': {
        const exp = JSON.stringify(step.assertExpected || '');
        lines.push(`        String actualText${idx} = wait.until(ExpectedConditions.visibilityOfElementLocated(${byExpr})).getText();`);
        lines.push(`        Assert.assertTrue(actualText${idx}.contains(${exp}), "Text assertion failed");`);
        break;
      }

      case 'wait':
        lines.push(`        try { Thread.sleep(${(step.waitDuration ?? 1) * 1000}); } catch (InterruptedException ignored) {}`);
        break;

      default:
        lines.push(`        wait.until(ExpectedConditions.elementToBeClickable(${byExpr})).click();`);
        break;
    }
  });

  lines.push(`    }`);
  lines.push('');
  lines.push(`    @AfterMethod`);
  lines.push(`    public void tearDown() {`);
  lines.push(`        if (driver != null) {`);
  lines.push(`            driver.quit();`);
  lines.push(`        }`);
  lines.push(`    }`);
  lines.push(`}`);
  return lines.join('\n');
}
