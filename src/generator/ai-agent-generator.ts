import { TestCaseModel, TestStep } from '../types/model';

/**
 * Synthesizes a natural language intent description for a single TestStep
 */
export function inferNaturalLanguageIntent(step: TestStep): string {
  const label = step.target?.labelText || step.target?.text || step.target?.name || step.target?.tagName || 'element';
  const cleanLabel = label.replace(/\s+/g, ' ').trim();

  switch (step.action) {
    case 'navigate':
      return `Navigate to "${step.value || 'target URL'}"`;
    case 'click':
      return `Click on the "${cleanLabel}" button or link`;
    case 'type':
      return `Type "${step.value || ''}" into the "${cleanLabel}" input field`;
    case 'clear':
      return `Clear the content of "${cleanLabel}"`;
    case 'select':
      return `Select option "${step.value || ''}" from the "${cleanLabel}" dropdown`;
    case 'checkbox':
    case 'radio':
      return `Select the "${cleanLabel}" checkbox or radio button`;
    case 'hover':
      return `Hover over the "${cleanLabel}" element`;
    case 'scroll':
      return `Scroll the page to view "${cleanLabel}"`;
    case 'assert_visible':
      return `Confirm that the "${cleanLabel}" element is clearly visible on the screen`;
    case 'assert_text':
      return `Verify that "${cleanLabel}" contains the text "${step.assertExpected || ''}"`;
    case 'wait':
      return `Wait for ${step.waitDuration ?? 2} seconds for network and UI to stabilize`;
    default:
      return `Interact with "${cleanLabel}"`;
  }
}

/**
 * Synthesizes a structured plain-English user story or scenario prompt
 */
export function generateNaturalLanguageScenario(testCase: TestCaseModel): string {
  const lines: string[] = [];
  lines.push(`Scenario: ${testCase.name || 'Automated User Journey'}`);
  lines.push(`Target URL: ${testCase.url || 'about:blank'}`);
  lines.push('');
  lines.push('User Steps:');
  testCase.steps.forEach((step, idx) => {
    lines.push(`  ${idx + 1}. ${inferNaturalLanguageIntent(step)}`);
  });
  return lines.join('\n');
}

/**
 * Generates an autonomous Python AI Agent script using `browser-use` & `langchain`
 */
export function generateBrowserUseAgent(testCase: TestCaseModel): string {
  const steps = testCase.steps || [];
  const taskIntents = steps.map((s) => inferNaturalLanguageIntent(s)).join(', then ');
  const fullTask = `Go to ${testCase.url || 'the website'}, then ${taskIntents}. Ensure all steps complete without errors and verify the final confirmation.`;

  const lines: string[] = [];
  lines.push(`"""`);
  lines.push(`Autonomous Browser-Use AI Agent: ${testCase.name || 'User Journey'}`);
  lines.push(`Generated by Chrome E2E Recorder (Master Edition)`);
  lines.push(`"""`);
  lines.push(`import asyncio`);
  lines.push(`import os`);
  lines.push(`from browser_use import Agent`);
  lines.push(`from langchain_openai import ChatOpenAI`);
  lines.push(``);
  lines.push(`async def main():`);
  lines.push(`    # 1. Initialize Vision-enabled LLM`);
  lines.push(`    llm = ChatOpenAI(`);
  lines.push(`        model="gpt-4o",`);
  lines.push(`        api_key=os.getenv("OPENAI_API_KEY")`);
  lines.push(`    )`);
  lines.push(``);
  lines.push(`    # 2. Define Autonomous Goal`);
  lines.push(`    task_description = (`);
  lines.push(`        ${JSON.stringify(fullTask)}`);
  lines.push(`    )`);
  lines.push(``);
  lines.push(`    # 3. Instantiate & Execute Autonomous Agent`);
  lines.push(`    agent = Agent(`);
  lines.push(`        task=task_description,`);
  lines.push(`        llm=llm,`);
  lines.push(`        use_vision=True`);
  lines.push(`    )`);
  lines.push(`    result = await agent.run()`);
  lines.push(`    print("[AGENT RESULT]:", result)`);
  lines.push(``);
  lines.push(`if __name__ == "__main__":`);
  lines.push(`    asyncio.run(main())`);
  return lines.join('\n');
}

/**
 * Generates an AI-driven Playwright Stagehand (TypeScript) script
 */
export function generateStagehandScript(testCase: TestCaseModel): string {
  const lines: string[] = [];
  const testName = testCase.name || 'Stagehand AI Test';
  const url = testCase.url || 'about:blank';

  lines.push(`import { Stagehand } from '@browserbase/stagehand';`);
  lines.push(`import { z } from 'zod';`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * AI-Driven Stagehand Autonomous Script: ${testName}`);
  lines.push(` */`);
  lines.push(`async function runStagehandAgent() {`);
  lines.push(`  const stagehand = new Stagehand({`);
  lines.push(`    env: 'LOCAL',`);
  lines.push(`    headless: process.env.HEADLESS === 'true',`);
  lines.push(`  });`);
  lines.push(``);
  lines.push(`  await stagehand.init();`);
  lines.push(`  const page = stagehand.page;`);
  lines.push(``);
  lines.push(`  try {`);
  lines.push(`    // Baseline Navigation`);
  lines.push(`    await page.goto('${url}');`);
  lines.push(``);

  testCase.steps.forEach((step, idx) => {
    const intent = inferNaturalLanguageIntent(step);
    lines.push(`    // Step ${idx + 1}: ${intent}`);

    if (step.action === 'click' || step.action === 'checkbox' || step.action === 'radio') {
      lines.push(`    await page.act(${JSON.stringify(intent)});`);
    } else if (step.action === 'type') {
      lines.push(`    await page.act(${JSON.stringify(`Type "${step.value || ''}" into the input field`)});`);
    } else if (step.action === 'assert_text' || step.action === 'assert_visible') {
      lines.push(`    const state${idx + 1} = await page.extract({`);
      lines.push(`      instruction: ${JSON.stringify(`Check if "${step.assertExpected || step.target?.text || ''}" is displayed on the page`)},`);
      lines.push(`      schema: z.object({ isPresent: z.boolean(), textFound: z.string().optional() })`);
      lines.push(`    });`);
      lines.push(`    console.log("[ASSERTION CHECK]:", state${idx + 1});`);
    } else {
      lines.push(`    await page.act(${JSON.stringify(intent)});`);
    }
    lines.push(``);
  });

  lines.push(`  } finally {`);
  lines.push(`    await stagehand.close();`);
  lines.push(`  }`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`runStagehandAgent();`);
  return lines.join('\n');
}
